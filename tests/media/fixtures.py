"""Generate synthetic, metadata-free image fixtures into the build directory."""
import io
from pathlib import Path
import sys
from PIL import Image


def main():
    target = Path(sys.argv[1])
    target.parent.mkdir(parents=True, exist_ok=True)
    fixtures = []
    for name, mode, size, color, fmt in [
        ("color_png", "RGB", (17, 9), (200, 100, 40), "PNG"),
        ("color_jpeg", "RGB", (17, 9), (200, 100, 40), "JPEG"),
        ("gray_jpeg", "L", (19, 13), 90, "JPEG"),
        ("alpha_png", "RGBA", (3, 2), (0, 0, 0, 0), "PNG"),
        ("palette_png", "P", (7, 5), 0, "PNG"),
        ("black_png", "L", (256, 256), 0, "PNG"),
        ("white_png", "L", (256, 256), 255, "PNG"),
        ("wide_png", "L", (256, 64), 127, "PNG"),
        ("tall_png", "L", (64, 256), 127, "PNG"),
        ("thin_png", "L", (4096, 1), 127, "PNG"),
        ("large_png", "L", (1025, 1025), 0, "PNG"),
        ("large_jpeg", "L", (1025, 1025), 0, "JPEG"),
        ("edge_png", "L", (4097, 1), 0, "PNG"),
        ("edge_jpeg", "L", (4097, 1), 0, "JPEG"),
        ("max_png", "L", (1024, 1024), 127, "PNG"),
    ]:
        image = Image.new(mode, size, color)
        if mode == "P":
            image.putpalette([200, 100, 40] + [0] * 765)
        encoded = io.BytesIO()
        image.save(encoded, format=fmt)
        data = encoded.getvalue()
        fixtures.append(f"static const unsigned char {name}[] = {{\n" +
                        "\n".join(",".join(str(b) for b in data[i:i+24]) + ","
                                  for i in range(0, len(data), 24)) + "\n};\n")
    target.write_text("/* Synthetic fixtures generated by tests/media/fixtures.py. */\n" +
                      "".join(fixtures), encoding="utf-8")


if __name__ == "__main__":
    main()
