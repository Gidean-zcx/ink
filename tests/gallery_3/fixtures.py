"""Synthetic pictures for gallery-3: the eight EXIF orientations, broken EXIF, a too-large JPEG, a WebP head.

As a script: write a C header for exif.c. As a module: the same pictures for run.py's card.
Every upright picture is 32 x 16 with four flat quarters: top-left 0, top-right 255, bottom-left 96, bottom-right 192.
"""
import io
import struct
import sys
from PIL import Image, ImageOps

QUARTERS = (0, 255, 96, 192)
# What turns the upright picture into the stored one, so that the orientation tag turns it back (PIL's exif_transpose
# is the reference: checked below for every case).
STORE = {1: None, 2: Image.Transpose.FLIP_LEFT_RIGHT, 3: Image.Transpose.ROTATE_180, 4: Image.Transpose.FLIP_TOP_BOTTOM,
         5: Image.Transpose.TRANSPOSE, 6: Image.Transpose.ROTATE_90, 7: Image.Transpose.TRANSVERSE, 8: Image.Transpose.ROTATE_270}


def upright():
    im = Image.new("L", (32, 16))
    for i, v in enumerate(QUARTERS):
        im.paste(v, ((i % 2) * 16, (i // 2) * 8, (i % 2) * 16 + 16, (i // 2) * 8 + 8))
    return im


def jpeg(im, orientation=None, taken=None, quality=95):
    exif = Image.Exif()
    if orientation:
        exif[0x0112] = orientation
    if taken:
        exif[0x8769] = {0x9003: taken}
    out = io.BytesIO()
    im.save(out, "JPEG", quality=quality, exif=exif.tobytes() if (orientation or taken) else b"")
    return out.getvalue()


def oriented(o, taken=None):
    im = upright()
    stored = im.transpose(STORE[o]) if STORE[o] is not None else im
    data = jpeg(stored, o, taken)
    back = ImageOps.exif_transpose(Image.open(io.BytesIO(data))).convert("L")
    assert back.size == (32, 16) and abs(back.getpixel((0, 0)) - 0) < 12 and abs(back.getpixel((31, 0)) - 255) < 12, o
    return data


def app1_offset(data):
    i = data.find(b"\xff\xe1")
    assert i > 0 and data[i + 4:i + 10] == b"Exif\0\0", "an EXIF APP1 segment"
    return i + 2  # its length field; "Exif\0\0" follows, then the TIFF block


def broken(data, kind):
    b = bytearray(data)
    at = app1_offset(b)
    tiff = at + 8
    little = b[tiff:tiff + 2] == b"II"
    pack = (lambda f, v: struct.pack("<" + f, v)) if little else (lambda f, v: struct.pack(">" + f, v))
    if kind == "ifd_out_of_range":
        b[tiff + 4:tiff + 8] = pack("I", 0xfffffff0)
    elif kind == "count_huge":
        ifd = struct.unpack(("<" if little else ">") + "I", bytes(b[tiff + 4:tiff + 8]))[0]
        b[tiff + ifd:tiff + ifd + 2] = pack("H", 0xffff)
    elif kind == "bad_magic":
        b[tiff + 2:tiff + 4] = pack("H", 43)
    elif kind == "orientation_9":
        i = bytes(b).find(pack("H", 0x0112), tiff)
        b[i + 8:i + 10] = pack("H", 9)
    elif kind == "length_past_end":
        b[at:at + 2] = struct.pack(">H", 0xfff0)
    return bytes(b)


def big_jpeg():
    return jpeg(Image.new("L", (1600, 1200), 200), quality=50)


def webp_head(w=64, h=48):
    vp8 = b"\x30\x01\x00\x9d\x01\x2a" + struct.pack("<HH", w, h) + b"\x00" * 12
    body = b"WEBP" + b"VP8 " + struct.pack("<I", len(vp8)) + vp8
    return b"RIFF" + struct.pack("<I", len(body)) + body


def c_array(name, data):
    rows = [", ".join(str(x) for x in data[i:i + 24]) for i in range(0, len(data), 24)]
    return f"static const uint8_t {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


if __name__ == "__main__":
    parts = ["/* Generated by tests/gallery_3/fixtures.py; synthetic pictures only. */\n#include <stdint.h>\n"]
    for o in range(1, 9):
        parts.append(c_array(f"orient_{o}", oriented(o, "2026:11:02 10:20:00" if o == 6 else None)))
    for kind in ("ifd_out_of_range", "count_huge", "bad_magic", "orientation_9", "length_past_end"):
        parts.append(c_array(f"broken_{kind}", broken(oriented(6), kind)))
    parts.append(c_array("big_jpeg", big_jpeg()))
    parts.append(c_array("webp_head", webp_head()))
    with open(sys.argv[1], "w") as f:
        f.write("".join(parts))
