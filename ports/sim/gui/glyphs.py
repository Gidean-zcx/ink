#!/usr/bin/env python3
"""Collect the non-ASCII characters of the window's sources into a header, so the window's font
atlas holds every character its labels use (on top of the common Chinese set).

  glyphs.py -o gui_glyphs.h gui_main.cpp ...
"""

import argparse


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("sources", nargs="+")
    a = ap.parse_args()
    chars = set()
    for path in a.sources:
        with open(path, encoding="utf-8") as f:
            chars.update(c for c in f.read() if ord(c) > 0x7F)
    text = "".join(sorted(chars))
    escaped = "".join("\\x%02x" % b for b in text.encode("utf-8"))
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("/* generated by ports/sim/gui/glyphs.py: characters used by the window's labels */\n")
        f.write('static const char kGuiGlyphs[] = "%s";\n' % escaped)


if __name__ == "__main__":
    main()
