#!/usr/bin/env python3
"""Write system/ui/shell/keyboard_symbols.h from the pinned upstream tables (keyboard-2, SOURCE.md).

Usage: gen_symbols.py <fcitx PopupPreset.kt> <fcitx PickerData.kt> <trime.yaml> > keyboard_symbols.h
Characters the keyboard font cannot draw (sans-44: ascii, punct, pinyin, gb2312) and repeats are dropped and
listed on stderr. A table only ever grows at its end: the recent-symbol ids are (table, index).
"""
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
spec = importlib.util.spec_from_file_location('fontgen', ROOT / 'tools/fontgen/fontgen.py')
fontgen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fontgen)
DRAWN = set(fontgen.charset('ascii,punct,pinyin,gb2312'))

popup_kt, picker_kt, trime = (Path(p).read_text(encoding='utf-8') for p in sys.argv[1:4])
lines = {'popup': popup_kt.splitlines(), 'picker': picker_kt.splitlines(), 'trime': trime.splitlines()}


def kotlin_strings(text):
    return [bytes(s, 'utf-8').decode('unicode_escape').encode('latin-1').decode('utf-8') if '\\' in s else s
            for s in re.findall(r'"((?:\\.|[^"\\])*)"', text)]


def keep(name, items):
    out, dropped = [], []
    for s in items:
        if not s or s in out:
            if s: dropped.append(s + '(重复)')
            continue
        if all(ord(c) in DRAWN for c in s): out.append(s)
        else: dropped.append(s)
    print(f'{name}: kept {len(out)}, dropped {" ".join(dropped) or "-"}', file=sys.stderr)
    return out


def yaml_keys(first, last):  # trime.yaml lines, 1-based inclusive
    block = '\n'.join(lines['trime'][first - 1:last])
    m = re.search(r'keys:\s*"([^"]*)"', block)
    if m: return list(m.group(1))
    return [re.sub(r'^\{ click: "(.*?)".*$', r'\1', l.strip()[2:]) for l in block.splitlines() if l.strip().startswith('- ')]


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


tables = [  # (C name, Chinese name, items) in storage order: append only
    ('SYM_CN', '中文', keep('cn trime.yaml:724-756', yaml_keys(724, 756))),
    ('SYM_EN', '英文', keep('ascii PickerData.kt:16-26', [s for s in kotlin_strings('\n'.join(lines['picker'][15:26])) if len(s) == 1 and 32 < ord(s) < 127])),
    ('SYM_MATH', '数学', keep('math trime.yaml:720-723', yaml_keys(720, 723))),
    # "m" is half of "m³", whose ³ the font cannot draw: alone it is no unit.
    ('SYM_UNIT', '单位', keep('unit trime.yaml:761-764', [c for c in yaml_keys(761, 764) if c != 'm'])),
    ('SYM_SHAPE', '图形', keep('symbol trime.yaml:757-760', yaml_keys(757, 760))),
    ('SYM_ORDINAL', '序号', keep('ordinal PickerData.kt:60-70', kotlin_strings('\n'.join(lines['picker'][59:70])))),
]
popup = {}
for l in lines['popup'][11:69]:
    m = re.match(r'\s*"(\w)" to arrayOf\((.*)\),?\s*$', l)
    if m: popup[m.group(1)] = keep('popup ' + m.group(1), kotlin_strings(m.group(2)))

print('/* Generated by docs/tasks/keyboard-2/gen_symbols.py from fcitx5-android eb5b5021 and Trime 76a9e763 (see')
print(' * docs/tasks/keyboard-2/SOURCE.md); data only. Tables grow only at their end: recent ids are (table, index). */')
print('/* ui-scale-runtime: dimension none Data only. */')
for name, title, items in tables:
    print(f'static const char *const {name}[] = {{ /* {title} */')
    for i in range(0, len(items), 12):
        print('    ' + ', '.join(c_string(s) for s in items[i:i + 12]) + ',')
    print('};')
print('/* Long-press alternates, lower case then upper case (PopupPreset.kt:12-69); the first is the swipe-up symbol. */')
print('static const char *const POPUP[52] = {')
for letters in ('abcdefghijklmnopqrstuvwxyz', 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'):
    for i in range(0, 26, 4):
        print('    ' + ', '.join(c_string(' '.join(popup[c])) for c in letters[i:i + 4]) + ',')
print('};')
