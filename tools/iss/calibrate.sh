#!/usr/bin/env bash
# ISS calibration ("Level 2"): one command from sources to cost classes.
#
#   bash tools/iss/calibrate.sh
#
# 1. builds the iss simulator (host C11 compiler)
# 2. fetches CoreMark, tinf and miniz at pinned revisions into tools/iss/build/src
#    (git over HTTPS; nothing is vendored into the repository)
# 3. cross-compiles CoreMark, the calibration kernels and an ISA self-test with
#    the Espressif RISC-V GCC (riscv32-esp-elf-gcc)
# 4. checks the simulator against the host on the ISA self-test
# 5. fits the timing model (scripts/calib.py) and runs the kernels
# 6. writes tools/iss/out/{costs.json,report.md,esp32s31.fitted.cfg}
#
# Environment: RV_GCC=/path/to/riscv32-esp-elf-gcc (otherwise PATH, then
# ~/.espressif/tools and /home/claude/sim/.espressif/tools are searched),
# CC (host compiler, default cc), PYTHON (default python3).
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
B=$HERE/build
OUT=$HERE/out
CC=${CC:-cc}
PYTHON=${PYTHON:-python3}

COREMARK_URL=https://github.com/eembc/coremark
COREMARK_REV=1f483d5b8316753a742cbf5590caf5bd0a4e4777
TINF_URL=https://github.com/jibsen/tinf
TINF_REV=57ffa1f1d5e3dde19011b2127bd26d01689b694b # v1.2.1
MINIZ_URL=https://github.com/richgel999/miniz
MINIZ_REV=77d0dce8627735138c51770d1799a1ef48f2117d # tag 3.1.2

log() { printf '== %s\n' "$*"; }

# --------------------------------------------------------------- toolchain
if [ -z "${RV_GCC:-}" ]; then
  if command -v riscv32-esp-elf-gcc >/dev/null 2>&1; then
    RV_GCC=$(command -v riscv32-esp-elf-gcc)
  else
    for d in "$HOME/.espressif/tools" /home/claude/sim/.espressif/tools; do
      [ -d "$d" ] || continue
      RV_GCC=$(find "$d" -name riscv32-esp-elf-gcc -type f 2>/dev/null | sort | tail -n 1)
      [ -n "$RV_GCC" ] && break
    done
  fi
fi
if [ -z "${RV_GCC:-}" ] || [ ! -x "$RV_GCC" ]; then
  echo "calibrate: riscv32-esp-elf-gcc not found (set RV_GCC)" >&2
  exit 1
fi
RV_BIN=$(dirname "$RV_GCC")
RV_SIZE=$RV_BIN/riscv32-esp-elf-size

mkdir -p "$B/src" "$B/elf" "$B/gen" "$OUT"

# --------------------------------------------------------------- 1. iss
log "build iss"
$CC -std=c11 -O2 -Wall -Wextra -Wshadow -Wno-unused-parameter -frounding-math \
  -o "$B/iss" "$HERE/src/iss.c" "$HERE/src/iss_cfg.c" "$HERE/src/iss_elf.c" "$HERE/src/main.c" -lm

# --------------------------------------------------------------- 2. sources
fetch() { # name url rev
  local dir=$B/src/$1
  if [ -d "$dir/.git" ] && [ "$(git -C "$dir" rev-parse HEAD 2>/dev/null)" = "$3" ]; then
    return
  fi
  log "fetch $1 @ ${3:0:12}"
  rm -rf "$dir"
  git init -q "$dir"
  git -C "$dir" fetch -q --depth 1 "$2" "$3"
  git -C "$dir" -c advice.detachedHead=false checkout -q FETCH_HEAD
}
fetch coremark "$COREMARK_URL" "$COREMARK_REV"
fetch tinf "$TINF_URL" "$TINF_REV"
fetch miniz "$MINIZ_URL" "$MINIZ_REV"
printf '/* generated by calibrate.sh (normally produced by miniz CMake) */\n#define MINIZ_EXPORT\n' >"$B/gen/miniz_export.h"

# --------------------------------------------------------------- 3. target builds
# ESP-IDF master builds the S31 with -march=rv32imafc_zicsr_zifencei_zaamo_zalrsc
# _xesploop_xespv -mabi=ilp32f -mtune=esp-base; GCC emits no xesploop/xespv code
# from C, so they are dropped. Zb/Zc are listed by the datasheet but not yet
# enabled by IDF for the S31: built as a sensitivity variant.
MARCH_IDF=rv32imafc_zicsr_zifencei_zaamo_zalrsc
MARCH_ZBZC=${MARCH_IDF}_zba_zbb_zbs_zcb_zcmp
TFLAGS="-mabi=ilp32f -mtune=esp-base -ffunction-sections -fdata-sections -fstrict-volatile-bitfields -std=gnu17"
IDF_DEFAULTS="-fno-jump-tables -fno-tree-switch-conversion" # ESP-IDF global defaults
CM_OPT="-O3 -fjump-tables -ftree-switch-conversion"        # espressif/coremark component
LDFLAGS="-nostartfiles -L$HERE/rt -Wl,--gc-sections -Wl,--no-warn-rwx-segments"
RT_SRC="$HERE/rt/crt0.S $HERE/rt/syscalls.c"
CM=$B/src/coremark

build_coremark() { # tag march
  local flags="-march=$2 $TFLAGS $CM_OPT"
  # shellcheck disable=SC2086
  "$RV_GCC" $flags -DPERFORMANCE_RUN=1 -DITERATIONS=50 "-DCOMPILER_FLAGS=\"$flags\"" \
    -I"$HERE/coremark" -I"$CM" -I"$HERE/rt" $LDFLAGS -T iram.ld $RT_SRC \
    "$HERE/coremark/core_portme.c" "$CM/core_list_join.c" "$CM/core_main.c" "$CM/core_matrix.c" \
    "$CM/core_state.c" "$CM/core_util.c" -lc -lm -lgcc -o "$B/elf/coremark-$1.elf"
}

build_kernels() { # tag march opt
  local T=$B/src/tinf/src M=$B/src/miniz
  # shellcheck disable=SC2086
  "$RV_GCC" -march=$2 $TFLAGS $3 $IDF_DEFAULTS -DMINIZ_NO_STDIO -DMINIZ_NO_TIME -DMINIZ_NO_ARCHIVE_APIS \
    -I"$HERE/rt" -I"$HERE/kernels" -I"$REPO/third_party/cjson" -I"$REPO/third_party/tlsf" -I"$T" -I"$M" -I"$B/gen" \
    -Wa,-I"$HERE/kernels/data" $LDFLAGS -T xip.ld $RT_SRC "$HERE/kernels/data.S" "$HERE/kernels/kmain.c" \
    "$HERE/kernels/k_mem.c" "$HERE/kernels/k_gfx.c" "$HERE/kernels/k_text.c" "$HERE/kernels/k_misc.c" \
    "$REPO/third_party/cjson/cJSON.c" "$REPO/third_party/tlsf/tlsf.c" "$T/tinflate.c" "$T/tinfzlib.c" "$T/adler32.c" \
    "$M/miniz_tinfl.c" -lc -lm -lgcc -o "$B/elf/kernels-$1.elf"
}

build_isatest() { # tag march
  # shellcheck disable=SC2086
  "$RV_GCC" -march=$2 $TFLAGS -O2 -ffp-contract=off -I"$HERE/rt" $LDFLAGS -T xip.ld $RT_SRC \
    "$HERE/kernels/isatest.c" -lc -lm -lgcc -o "$B/elf/isatest-$1.elf"
}

log "cross-compile ($("$RV_GCC" -dumpversion), $(basename "$RV_GCC"))"
build_coremark idf "$MARCH_IDF"
build_coremark zbzc "$MARCH_ZBZC"
build_kernels O2 "$MARCH_IDF" -O2
build_kernels Os "$MARCH_IDF" -Os
build_kernels O2-zbzc "$MARCH_ZBZC" -O2
build_isatest idf "$MARCH_IDF"
build_isatest zbzc "$MARCH_ZBZC"
"$RV_SIZE" "$B/elf/coremark-idf.elf" "$B/elf/kernels-O2.elf" | sed 's/^/   /'

# --------------------------------------------------------------- 4. ISA self-test
log "ISA self-test (host vs iss)"
$CC -std=gnu11 -O2 -ffp-contract=off -o "$B/isatest-host" "$HERE/kernels/isatest.c" -lm
want=$("$B/isatest-host")
for t in idf zbzc; do
  got=$("$B/iss" "$B/elf/isatest-$t.elf" 2>/dev/null)
  if [ "$got" != "$want" ]; then
    echo "calibrate: ISA self-test mismatch for $t: iss '$got', host '$want'" >&2
    exit 1
  fi
done
echo "   $want (host = iss, both ISA variants)"

# CoreMark must validate (the 10 s rule is meaningless in a simulator)
cm_out=$("$B/iss" "$B/elf/coremark-idf.elf" 2>/dev/null)
for crc in "seedcrc          : 0xe9f5" "crclist       : 0xe714" "crcmatrix     : 0x1fd7" "crcstate      : 0x8e3a"; do
  if ! grep -qF "$crc" <<<"$cm_out"; then
    echo "calibrate: CoreMark validation failed ($crc missing)" >&2
    echo "$cm_out" >&2
    exit 1
  fi
done
echo "   CoreMark CRCs valid"

# --------------------------------------------------------------- 5/6. fit, run, report
cat >"$B/meta.json" <<EOF
{
  "toolchain": "$("$RV_GCC" --version | head -n 1)",
  "march_idf": "$MARCH_IDF",
  "march_zbzc": "$MARCH_ZBZC",
  "kernel_flags": "$TFLAGS -O2 $IDF_DEFAULTS",
  "coremark_flags": "$TFLAGS $CM_OPT, code+data in internal SRAM, ITERATIONS=50",
  "coremark": "$COREMARK_URL @ $COREMARK_REV",
  "tinf": "$TINF_URL @ $TINF_REV",
  "miniz": "$MINIZ_URL @ $MINIZ_REV",
  "cjson": "third_party/cjson $(cat "$REPO/third_party/cjson/UPSTREAM_TAG")",
  "tlsf": "third_party/tlsf $(cat "$REPO/third_party/tlsf/UPSTREAM_COMMIT")",
  "base_config": "tools/iss/timing/esp32s31.cfg"
}
EOF
log "fit timing model, run kernels, write report"
"$PYTHON" "$HERE/scripts/calib.py" --iss "$B/iss" --elf-dir "$B/elf" --base "$HERE/timing/esp32s31.cfg" \
  --profile "$REPO/simulator/profiles/metalio-plus.json" --runs "$B/runs" --out "$OUT" --meta "$B/meta.json"
log "done: $OUT/costs.json, $OUT/report.md, $OUT/esp32s31.fitted.cfg"
