#!/usr/bin/env python3
"""Check the translation tables and generate the firmware's lookup header.

Chinese is the source language: the Chinese text in the code is the key. Each other language is one
file `assets/i18n/<code>.tsv`, UTF-8, one entry per line: `Chinese<TAB>translation`. Blank lines and
lines starting with `#` are skipped; the line `@name<TAB>English` names the language in its own words
(what the language setting shows). `\\n`, `\\t` and `\\\\` are escapes in both columns.

Checks (any failure stops the build): a line without exactly one tab or with an empty side, a key
given twice, a key or translation that is not valid UTF-8, printf placeholders (`%d`, `%s`, `%lld`,
`%.8s` ...) that differ between the two sides, a missing `@name`. With `--sources`, every literal
`TR("...")` / `TR_NOOP("...")` in those C files must have an entry in every language.
"""
import argparse
from pathlib import Path
import re
import sys

PLACEHOLDER = re.compile(r'%(?:%|[-+ 0#]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|h|ll|l|z|j|t)?[diouxXcsfeEgGp])')
LITERAL = re.compile(r'\bTR(?:_NOOP)?\(\s*"((?:[^"\\\n]|\\.)*)"\s*\)')
C_ESCAPES = {'n': '\n', 't': '\t', '\\': '\\', '"': '"', "'": "'"}


def unescape(text):
    return re.sub(r'\\(.)', lambda m: C_ESCAPES.get(m[1], '\\' + m[1]), text)


def c_string(text):
    out = []
    for ch in text:
        if ch in '\\"': out.append('\\' + ch)
        elif ch == '\n': out.append('\\n')
        elif ch == '\t': out.append('\\t')
        elif ord(ch) < 32: out.append('\\%03o' % ord(ch))
        else: out.append(ch)
    # "?" next to "?" could form a trigraph; split string literals there.
    return '"' + ''.join(out).replace('??', '?""?') + '"'


def placeholders(text):
    return [p for p in PLACEHOLDER.findall(text) if p != '%%']


def load(path):
    errors, entries, name = [], {}, None
    try:
        lines = path.read_bytes().decode('utf-8').split('\n')
    except UnicodeDecodeError as e:
        return None, None, [f'{path.name}: not UTF-8 ({e})']
    for number, line in enumerate(lines, 1):
        line = line.rstrip('\r')
        where = f'{path.name}:{number}'
        if not line.strip() or line.startswith('#'):
            continue
        cols = line.split('\t')
        if len(cols) != 2 or not cols[0] or not cols[1]:
            errors.append(f'{where}: need exactly "Chinese<TAB>translation", both non-empty')
            continue
        if cols[0] == '@name':
            name = cols[1]
            continue
        key, value = unescape(cols[0]), unescape(cols[1])
        if key in entries:
            errors.append(f'{where}: duplicate key {key!r}')
            continue
        if placeholders(key) != placeholders(value):
            errors.append(f'{where}: placeholders differ: {placeholders(key)} vs {placeholders(value)} in {key!r}')
            continue
        entries[key] = value
    if not name:
        errors.append(f'{path.name}: missing "@name<TAB>language name" line')
    return name, entries, errors


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('tables', nargs='+', type=Path, help='assets/i18n/<code>.tsv files')
    ap.add_argument('--header', type=Path, help='write the generated C header here')
    ap.add_argument('--sources', nargs='*', type=Path, default=[], help='C files whose TR() keys must all be translated')
    a = ap.parse_args()
    langs, errors = [], []
    for path in sorted(a.tables):
        name, entries, problems = load(path)
        errors += problems
        langs.append((path.stem, name, entries or {}))
    for source in a.sources:
        keys = {unescape(k) for k in LITERAL.findall(source.read_text(encoding='utf-8'))}
        for code, _, entries in langs:
            for key in sorted(keys - set(entries)):
                errors.append(f'{source.name}: {code} has no translation for {key!r}')
    if errors:
        sys.exit('i18n tables are wrong:\n  ' + '\n  '.join(errors))
    if a.header:
        out = ['/* Generated by tools/i18n/i18n_gen.py from the assets/i18n tables; do not edit. */',
               '/* Sorted by the Chinese key\'s bytes (strcmp order); const, so it stays in flash. */']
        for code, _, entries in langs:
            if not entries: continue
            out.append(f'static const ink_i18n_pair_t I18N_{code.upper()}[] = {{')
            for key in sorted(entries, key=lambda k: k.encode()):
                out.append(f'    {{{c_string(key)}, {c_string(entries[key])}}},')
            out.append('};')
        out.append('static const ink_i18n_lang_t I18N_LANGS[] = {')
        out.append('    {"zh", "中文", NULL, 0},')
        for code, name, entries in langs:
            table = f'I18N_{code.upper()}'
            out.append(f'    {{{c_string(code)}, {c_string(name)}, ' +
                       (f'{table}, sizeof {table} / sizeof *{table}}},' if entries else 'NULL, 0},'))
        out.append('};')
        out.append('static const char *const I18N_NAMES[] = {"中文", ' +
                   ''.join(c_string(name) + ', ' for _, name, _ in langs) + 'NULL};')
        text = '\n'.join(out) + '\n'
        a.header.parent.mkdir(parents=True, exist_ok=True)
        a.header.write_text(text, encoding='utf-8')
    print(f'i18n: {", ".join(f"{code} {len(entries)} entries" for code, _, entries in langs)}')


if __name__ == '__main__':
    main()
