#!/usr/bin/env python3
"""Files the firmware needs on the storage card (D-138), made at build time.

  bundle  --spec tools/card_files.json --noto TTC --face N --out DIR   make the files: DIR/files/<n>, DIR/manifest.json
  header  --manifest DIR/manifest.json --out .../ink/card_files_manifest.h   the C table the firmware checks the card with
  verify  --manifest DIR/manifest.json --header H   both say the same (exit 1 if not)
  python  CANDIDATE...   print the first interpreter that can import fontTools (exit 1: none)

The digest: for each entry in order "<path> <size> <sha256hex> <app>\\n", sha256 of it all, the first 16 hex digits
(docs/system/card-files.md). Hashes are never committed: another fontTools may make other bytes.
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PREFIXES = ("/content/fonts/", "/content/.system/")
MAX_ENTRIES = 8          # INK_CARD_FILES_MAX in system/include/ink/sys/card_files.h
MAX_FILE = 5 * 1024 * 1024
FIELDS = ("path", "size", "sha256", "app")


def path_problem(path):
    if not isinstance(path, str) or not path.startswith(PREFIXES):
        return "not under /content/fonts/ or /content/.system/"
    if ".." in path or "//" in path or "\\" in path or any(ord(c) < 0x20 or ord(c) == 0x7F for c in path):
        return "has .., //, a backslash or a control character"
    if path.endswith(".part") or path.endswith("/"):
        return "ends in .part or /"
    if len(path.encode()) >= 120:  # INK_FS_PATH_MAX 128 with ".part"
        return "too long"
    return None


def check(entries, sized=True):
    if len(entries) > MAX_ENTRIES:
        raise SystemExit(f"card files: {len(entries)} entries, at most {MAX_ENTRIES}")
    seen = set()
    for e in entries:
        problem = path_problem(e.get("path"))
        if problem:
            raise SystemExit(f"card files: {e.get('path')!r} {problem}")
        if e["path"] in seen:
            raise SystemExit(f"card files: {e['path']} twice")
        seen.add(e["path"])
        if not re.fullmatch(r"[a-z][a-z0-9_]{0,15}", str(e.get("app", ""))):
            raise SystemExit(f"card files: {e['path']}: bad app id {e.get('app')!r}")
        if sized:
            if not 0 <= int(e["size"]) <= MAX_FILE:
                raise SystemExit(f"card files: {e['path']} is {e['size']} bytes, at most {MAX_FILE}")
            if not re.fullmatch(r"[0-9a-f]{64}", e["sha256"]):
                raise SystemExit(f"card files: {e['path']}: bad sha256")


def digest(entries):
    text = "".join(f"{e['path']} {e['size']} {e['sha256']} {e['app']}\n" for e in entries)
    return hashlib.sha256(text.encode()).hexdigest()[:16]


def make_file(kind, noto, face, work):
    font = work / "InkSC.ttf"
    if kind in ("mogo_font", "mogo_font_ofl"):
        if not font.exists():
            sys.path.insert(0, str(Path(__file__).resolve().parent))
            import mogo_font  # fontTools: only the bundle step needs it
            mogo_font.convert(Path(noto), font, face)
        return font if kind == "mogo_font" else font.with_suffix(".OFL.txt")
    raise SystemExit(f"card files: unknown make {kind!r}")


def bundle(a):
    spec = json.loads(Path(a.spec).read_text())
    check(spec["entries"], sized=False)
    out = Path(a.out)
    shutil.rmtree(out / "files", ignore_errors=True)
    (out / "files").mkdir(parents=True)
    entries = []
    with tempfile.TemporaryDirectory() as tmp:
        for n, e in enumerate(spec["entries"]):
            data = make_file(e["make"], a.noto, a.face, Path(tmp)).read_bytes()
            (out / "files" / str(n)).write_bytes(data)
            entries.append({"path": e["path"], "size": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                            "app": e["app"], "file": f"files/{n}"})
    check(entries)
    manifest = {"version": 1, "digest": digest(entries), "entries": entries}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")


def load(manifest_path):
    m = json.loads(Path(manifest_path).read_text())
    if m.get("version") != 1:
        raise SystemExit("card files: manifest version is not 1")
    check(m["entries"])
    if m["digest"] != digest(m["entries"]):
        raise SystemExit("card files: the manifest's digest does not match its entries")
    return m


def c_text(m):
    rows = []
    for e in m["entries"]:
        sha = ",".join(f"0x{b:02x}" for b in bytes.fromhex(e["sha256"]))
        rows.append(f'    {{"{e["path"]}", {e["size"]}u, {{{sha}}}, "{e["app"]}"}},')
    return "\n".join([
        "/* Generated by tools/card_files.py from tools/card_files.json (D-138): do not edit. */",
        "#ifndef INK_CARD_FILES_MANIFEST_H", "#define INK_CARD_FILES_MANIFEST_H", "#include <stdint.h>",
        "typedef struct { const char *path; uint32_t size; uint8_t sha256[32]; const char *app; } ink_card_file_t;",
        "static const ink_card_file_t INK_CARD_FILES[] = {", *(rows or ['    {"", 0u, {0}, ""},']), "};",
        f"#define INK_CARD_FILES_COUNT {len(m['entries'])}", f'#define INK_CARD_FILES_DIGEST "{m["digest"]}"',
        "#endif", ""])


def header(a):
    text, out = c_text(load(a.manifest)), Path(a.out)
    if not out.exists() or out.read_text() != text:  # unchanged: nothing recompiles
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)


def parse_header(text):
    found = re.search(r'#define INK_CARD_FILES_DIGEST "([0-9a-f]{16})"', text)
    count = re.search(r"#define INK_CARD_FILES_COUNT (\d+)", text)
    rows = re.findall(r'\{"([^"]*)", (\d+)u, \{([^}]*)\}, "([^"]*)"\}', text)
    entries = [{"path": p, "size": int(s), "sha256": "".join(b.strip()[2:] for b in sha.split(",")), "app": app}
               for p, s, sha, app in rows][:int(count[1]) if count else 0]
    return (found[1] if found else None), entries


def verify(a):
    m = load(a.manifest)
    got_digest, got = parse_header(Path(a.header).read_text())
    want = [{k: e[k] for k in FIELDS} for e in m["entries"]]
    if got_digest != m["digest"] or got != want:
        raise SystemExit(f"card files: {a.header} does not match {a.manifest} ({got_digest} / {m['digest']})")
    print(f"card files: header and manifest agree, digest {m['digest']}, {len(want)} entries")


def pick_python(a):
    for candidate in a.candidates:
        path = shutil.which(candidate)
        if path and subprocess.run([path, "-c", "import fontTools"], capture_output=True).returncode == 0:
            print(path)
            return
    raise SystemExit(1)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("bundle")
    b.add_argument("--spec", required=True)
    b.add_argument("--noto", required=True)
    b.add_argument("--face", type=int, default=2)
    b.add_argument("--out", required=True)
    h = sub.add_parser("header")
    h.add_argument("--manifest", required=True)
    h.add_argument("--out", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--manifest", required=True)
    v.add_argument("--header", required=True)
    p = sub.add_parser("python")
    p.add_argument("candidates", nargs="+")
    a = ap.parse_args(argv)
    {"bundle": bundle, "header": header, "verify": verify, "python": pick_python}[a.cmd](a)


if __name__ == "__main__":
    main()
