#!/bin/bash
# Fetch the third-party sources the calibration kernels need (tinf, miniz) into tools/iss/build,
# at the revisions tools/iss/calibrate.sh pins, so the device runs the code the ISS measured.
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ISS=$(cd "$HERE/../iss" && pwd)
eval "$(grep -E '^(TINF|MINIZ)_(URL|REV)=' "$ISS/calibrate.sh" | sed 's/ *#.*//')"
B=$ISS/build
mkdir -p "$B/src" "$B/gen"
fetch() { # name url rev (as calibrate.sh)
  local dir=$B/src/$1
  if [ -d "$dir/.git" ] && [ "$(git -C "$dir" rev-parse HEAD 2>/dev/null)" = "$3" ]; then return; fi
  echo "== fetch $1 @ ${3:0:12}"
  rm -rf "$dir"
  git init -q "$dir"
  git -C "$dir" fetch -q --depth 1 "$2" "$3"
  git -C "$dir" -c advice.detachedHead=false checkout -q FETCH_HEAD
}
fetch tinf "$TINF_URL" "$TINF_REV"
fetch miniz "$MINIZ_URL" "$MINIZ_REV"
printf '/* generated by fetch_deps.sh (normally produced by miniz CMake) */\n#define MINIZ_EXPORT\n' >"$B/gen/miniz_export.h"
